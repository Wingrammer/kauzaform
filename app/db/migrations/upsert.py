from datetime import datetime
from main import supabase

# Execute the migrations
with open("generated_migration.py", "r") as file:
    migrations = file.read()

# Create a unique migration identifier based on the current datetime
migration_id = datetime.utcnow().strftime("%Y%m%d%H%M%S")
migration_script = f"app/db/migrations/{migration_id}.py"

with open(migration_script, "w") as file:
    file.write("# Autogenerated migration script\n")
    file.write(migrations)

# Execute the migration script
with open(migration_script, "r") as file:
    migration_code = file.read()

# Create or update the tables
supabase.table().upsert([{"id": migration_id, "migration_code": migration_code}], returning="minimal").execute()